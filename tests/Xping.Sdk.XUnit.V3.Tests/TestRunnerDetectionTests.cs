using Xping.Sdk.Core.Services.LocalStore;

namespace Xping.Sdk.XUnit.V3.Tests;

/// <summary>
/// The stacks, arguments and environments here are what a real xUnit v3 4.0.2 test process saw when
/// it created its framework, on each runner.
/// </summary>
public sealed class TestRunnerDetectionTests
{
    private static readonly string[] ConsoleRunnerStack =
    [
        "Xunit.v3.RegisteredEngineConfig",
        "Xunit.Runner.InProc.SystemConsole.ProjectAssemblyRunner",
        "Xunit.Runner.InProc.SystemConsole.ConsoleRunner",
        "Xunit.AutoGenerated._2cHOF9WIu.XunitAutoGeneratedEntryPoint",
    ];

    [Fact]
    public void DotnetTestOnTheTestingPlatform_IsMtp()
    {
        string?[] stack =
        [
            "Xunit.v3.RegisteredEngineConfig",
            "Xunit.Runner.InProc.SystemConsole.ProjectAssemblyRunner",
            "Xunit.MicrosoftTestingPlatform.TestPlatformTestFramework+<>c__DisplayClass22_0",
            "Xunit.MicrosoftTestingPlatform.TestPlatformTestFramework",
        ];

        string? runner = TestRunnerDetection.Detect(
            stack,
            ["Shop.Tests.dll", "--filter-method", "Shop.Tests.Cart", "--server", "dotnettestcli"],
            ["TESTINGPLATFORM_DOTNETTEST_EXECUTIONID"]);

        Assert.Equal(LocalSessionProperties.TestingPlatformRunner, runner);
    }

    [Fact]
    public void XunitRunnerVisualStudio_LaunchingTheExecutableWithAResponseFile_IsVSTest()
    {
        string? runner = TestRunnerDetection.Detect(
            ConsoleRunnerStack,
            ["Shop.Tests.dll", "@@", "/tmp/tmpHcwWqF.tmp"],
            ["VSTEST_DOTNET_ROOT_PATH", "VSTEST_MSBUILD_NOLOGO", "PATH"]);

        Assert.Equal(LocalSessionProperties.VSTestRunner, runner);
    }

    [Fact]
    public void AutomatedModeWithoutVSTestsEnvironment_IsUnknown()
    {
        // xUnit's own console and MSBuild runners launch the executable this way too, and take
        // different arguments from dotnet test.
        Assert.Null(TestRunnerDetection.Detect(ConsoleRunnerStack, ["Shop.Tests.dll", "-automated"], ["PATH"]));
    }

    [Fact]
    public void TheExecutableRunByHand_IsUnknown()
    {
        Assert.Null(TestRunnerDetection.Detect(ConsoleRunnerStack, ["Shop.Tests.dll", "-method", "Shop.Tests.Cart"], ["VSTEST_HOST_DEBUG"]));
    }
}
